using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

internal sealed partial class JavaScriptEmitter
{
    private readonly StringBuilder _output = new();
    private readonly CSharpCompilation _compilation;
    private readonly GeneratedNameAllocator _names = new();
    private readonly HelperRegistry _helpers;
    private readonly ImportRegistry _imports;
    private readonly Dictionary<ISymbol, string> _userIdentifiers = new(SymbolEqualityComparer.Default);
    private readonly Dictionary<IMethodSymbol, string> _userMethods = new(SymbolEqualityComparer.Default);
    private readonly Queue<IMethodSymbol> _pendingUserMethods = new();
    private readonly HashSet<IMethodSymbol> _emittedUserMethods = new(SymbolEqualityComparer.Default);
    private readonly Dictionary<INamedTypeSymbol, string> _userTypes = new(SymbolEqualityComparer.Default);
    private readonly Queue<INamedTypeSymbol> _pendingUserTypes = new();
    private readonly HashSet<INamedTypeSymbol> _emittedUserTypes = new(SymbolEqualityComparer.Default);
    private readonly HashSet<(INamedTypeSymbol Type, int Mode)> _jsonReaders = [];
    private readonly Queue<(INamedTypeSymbol Type, int Mode)> _pendingJsonReaders = new();
    private readonly Dictionary<IMethodSymbol, string> _userInstanceMethods = new(SymbolEqualityComparer.Default);
    private readonly Dictionary<ISymbol, string> _userMemberNames = new(SymbolEqualityComparer.Default);
    private readonly HashSet<INamedTypeSymbol> _preparedUserMemberNames = new(SymbolEqualityComparer.Default);
    private readonly Stack<string> _caughtExceptions = new();
    private SemanticModel _model = null!;
    // The statement or declaration being emitted, used to locate diagnostics raised without a node.
    private SyntaxNode? _diagnosticNode;
    private JavaScriptEmitter(CSharpCompilation compilation)
    {
        _compilation = compilation;
        _helpers = new HelperRegistry(_names);
        _imports = new ImportRegistry(_names);
    }

    public static string Emit(CSharpCompilation compilation)
    {
        var emitter = new JavaScriptEmitter(compilation);
        try
        {
            return emitter.EmitModule(compilation);
        }
        catch (NotSupportedException exception)
        {
            throw WorkerDiagnostics.WithLocation(exception, emitter._diagnosticNode);
        }
    }

    private string EmitModule(CSharpCompilation compilation)
    {
        var program = WorkerDiscovery.Discover(compilation);
        var emitter = this;
        foreach (var declaration in program.DurableObjects.Concat(program.WorkerEntrypoints).Concat(program.HtmlHandlers))
            _runtimeInterfaceTypes.Add(compilation.GetSemanticModel(declaration.SyntaxTree).GetDeclaredSymbol(declaration)!);

        emitter._output.AppendLine("// Generated by Workers.Compiler.");
        foreach (var htmlHandler in program.HtmlHandlers)
            emitter.EmitHtmlHandler(htmlHandler);
        foreach (var durableObject in program.DurableObjects)
            emitter.EmitRuntimeClass(durableObject, "DurableObject");
        foreach (var workerEntrypoint in program.WorkerEntrypoints)
            emitter.EmitRuntimeClass(workerEntrypoint, "WorkerEntrypoint");
        foreach (var handler in program.Events)
            emitter.EmitHandler(handler.Name, handler.Method);
        do
        {
            emitter.EmitPendingRuntimeInterfaceCalls();
            emitter.EmitUserCode();
            emitter.EmitPendingJsonReaders();
            emitter.EmitPendingRpcReaders();
            emitter.PrepareGenericDispatch();
            emitter.PrepareObjectTextDispatch();
            emitter.PrepareRecordTextDispatch();
            emitter.PrepareRecordHashDispatch();
            emitter.PrepareUserKeyDispatch();
        } while (emitter._pendingUserTypes.Count != 0 || emitter._pendingUserMethods.Count != 0
            || emitter._pendingRecordHashes.Count != 0 || emitter._pendingRecordTextFunctions.Count != 0 || emitter._pendingRecordPrintFunctions.Count != 0
            || emitter._pendingRpcReaders.Count != 0 || emitter._pendingRuntimeInterfaceCalls.Count != 0);

        emitter.EmitGenericDispatchers();
        emitter.EmitRecordHashDispatch();
        emitter.EmitVariantInterfaceMembers();
        emitter.EmitRuntimeInterfaceMarkers();

        emitter._output.Append(emitter._helpers.Emit());
        if (emitter._helpers.IsRequired(JavaScriptHelper.RpcArguments))
            foreach (var name in emitter._userTypes.Values)
                emitter._output.Append(emitter._helpers.Name("rpcClasses")).Append(".add(").Append(name).AppendLine(".prototype);");
        emitter._output.Insert(0, emitter.EmitBuiltInExceptionTypes());
        if (emitter._usesPlainRecordIdentity)
            emitter._output.Insert(0, $"const {emitter.PlainRecordIdentitySlot} = Symbol();" + Environment.NewLine);
        emitter.EmitDelegateMethodAliases();
        emitter.EmitUserKeyDispatch();
        emitter._output.Append(emitter._routeDeclarations);

        if (program.Events.Count != 0)
            emitter._output.Append("export default { ")
                .Append(string.Join(", ", program.Events.Select(handler => $"{handler.Name}: {emitter.EventName(handler.Name)}")))
                .AppendLine(" };");
        return emitter._imports.Emit() + emitter.EmitObjectTextSupport() + (emitter._usesHierarchyConstruction
            ? $"const {emitter.HierarchySkipToken} = Symbol();\n" : "")
            + string.Concat(emitter._requestedInterfaces.ToArray().Select(type =>
                $"const {emitter.InterfaceMarker(type)} = Symbol();\n")) + emitter._output;
    }

}
