using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace Workers.Build;

/// <summary>Generates the JavaScript module that Cloudflare Workers loads.</summary>
internal static class ModuleWriter
{
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        WriteIndented = true,
        Converters = { new JsonStringEnumConverter() }
    };

    /// <summary>Creates a JavaScript module for the provided build manifest.</summary>
    public static string WriteModule(BuildManifest manifest, ModuleOptions? options = null)
    {
        ArgumentNullException.ThrowIfNull(manifest);
        options ??= ModuleOptions.Default;

        if (manifest.Entrypoints.Count == 0 && manifest.DurableObjects.Count == 0)
            throw new EntrypointException("At least one Worker entrypoint or Durable Object export is required.");

        var adapterModule = ToJavaScriptString(options.RuntimeAdapterModule);
        var manifestJson = JsonSerializer.Serialize(manifest, JsonOptions);

        var builder = new StringBuilder()
            .AppendLine("// <auto-generated />")
            .Append("import dotnet from ")
            .Append(adapterModule)
            .AppendLine(";");

        if (manifest.DurableObjects.Count > 0)
            builder.AppendLine("import { DurableObject } from \"cloudflare:workers\";");

        builder
            .AppendLine()
            .Append("const manifest = ")
            .Append(manifestJson)
            .AppendLine(";")
            .AppendLine("let workerPromise;")
            .AppendLine()
            .AppendLine("async function getWorker() {")
            .AppendLine("  workerPromise ??= dotnet(manifest);")
            .AppendLine("  return await workerPromise;")
            .AppendLine("}")
            .AppendLine();

        AppendDurableObjects(builder, manifest.DurableObjects);

        builder
            .AppendLine("export default {");

        AppendHandlers(builder, manifest.Entrypoints);

        return builder
            .AppendLine("};")
            .ToString();
    }

    private static void AppendHandlers(StringBuilder builder, IReadOnlyList<Entrypoint> entrypoints)
    {
        var handlers = entrypoints
            .OrderBy(static entrypoint => entrypoint.Kind)
            .Select(ToHandler)
            .ToArray();

        for (var index = 0; index < handlers.Length; index++)
        {
            builder.Append(handlers[index]);
            builder.AppendLine(index == handlers.Length - 1 ? "" : ",");
        }
    }

    private static void AppendDurableObjects(
        StringBuilder builder,
        IReadOnlyList<DurableObjectEntrypoint> durableObjects)
    {
        foreach (var durableObject in durableObjects.OrderBy(static durableObject => durableObject.ExportName, StringComparer.Ordinal))
        {
            var exportName = durableObject.ExportName;
            var exportNameLiteral = ToJavaScriptString(exportName);
            builder
                .Append("export class ")
                .Append(exportName)
                .AppendLine(" extends DurableObject {")
                .AppendLine("  constructor(ctx, env) {")
                .AppendLine("    super(ctx, env);")
                .AppendLine("    this.ctx = ctx;")
                .AppendLine("    this.env = env;")
                .AppendLine("  }");

            if (durableObject.FetchMethodName is not null)
            {
                builder
                    .AppendLine()
                    .AppendLine("  async fetch(request) {")
                    .AppendLine("    const worker = await getWorker();")
                    .Append("    return await worker.durableObjectFetch(")
                    .Append(exportNameLiteral)
                    .AppendLine(", this.ctx, request, this.env);")
                    .AppendLine("  }");
            }

            if (durableObject.AlarmMethodName is not null)
            {
                builder
                    .AppendLine()
                    .AppendLine("  async alarm(alarmInfo) {")
                    .AppendLine("    const worker = await getWorker();")
                    .Append("    await worker.durableObjectAlarm(")
                    .Append(exportNameLiteral)
                    .AppendLine(", this.ctx, this.env, alarmInfo ?? null);")
                    .AppendLine("  }");
            }

            if (durableObject.WebSocketMessageMethodName is not null)
            {
                builder
                    .AppendLine()
                    .AppendLine("  async webSocketMessage(ws, message) {")
                    .AppendLine("    const worker = await getWorker();")
                    .Append("    await worker.durableObjectWebSocketMessage(")
                    .Append(exportNameLiteral)
                    .AppendLine(", this.ctx, ws, message, this.env);")
                    .AppendLine("  }");
            }

            if (durableObject.WebSocketCloseMethodName is not null)
            {
                builder
                    .AppendLine()
                    .AppendLine("  async webSocketClose(ws, code, reason, wasClean) {")
                    .AppendLine("    const worker = await getWorker();")
                    .Append("    await worker.durableObjectWebSocketClose(")
                    .Append(exportNameLiteral)
                    .AppendLine(", this.ctx, ws, code, reason, wasClean, this.env);")
                    .AppendLine("  }");
            }

            if (durableObject.WebSocketErrorMethodName is not null)
            {
                builder
                    .AppendLine()
                    .AppendLine("  async webSocketError(ws, error) {")
                    .AppendLine("    const worker = await getWorker();")
                    .Append("    await worker.durableObjectWebSocketError(")
                    .Append(exportNameLiteral)
                    .AppendLine(", this.ctx, ws, error, this.env);")
                    .AppendLine("  }");
            }

            foreach (var rpcMethod in durableObject.RpcMethods.OrderBy(static method => method.Name, StringComparer.Ordinal))
            {
                builder
                    .AppendLine()
                    .Append("  async ")
                    .Append(rpcMethod.Name)
                    .AppendLine("(...args) {")
                    .AppendLine("    const worker = await getWorker();")
                    .Append("    return await worker.durableObjectRpc(")
                    .Append(exportNameLiteral)
                    .Append(", ")
                    .Append(ToJavaScriptString(rpcMethod.Name))
                    .AppendLine(", this.ctx, this.env, args);")
                    .AppendLine("  }");
            }

            builder
                .AppendLine("}")
                .AppendLine();
        }
    }

    private static string ToHandler(Entrypoint entrypoint) =>
        entrypoint.Kind switch
        {
            EntrypointKind.Fetch => """
              async fetch(request, env, ctx) {
                const worker = await getWorker();
                return await worker.fetch(request, env, ctx);
              }
            """,
            EntrypointKind.Scheduled => """
              async scheduled(event, env, ctx) {
                const worker = await getWorker();
                await worker.scheduled(event, env, ctx);
              }
            """,
            EntrypointKind.Queue => """
              async queue(batch, env, ctx) {
                const worker = await getWorker();
                await worker.queue(batch, env, ctx);
              }
            """,
            EntrypointKind.Email => """
              async email(message, env, ctx) {
                const worker = await getWorker();
                await worker.email(message, env, ctx);
              }
            """,
            EntrypointKind.Tail => """
              async tail(events, env, ctx) {
                const worker = await getWorker();
                await worker.tail(events, env, ctx);
              }
            """,
            _ => throw new EntrypointException($"Unsupported entrypoint kind '{entrypoint.Kind}'.")
        };

    private static string ToJavaScriptString(string value) =>
        JsonSerializer.Serialize(value);
}
